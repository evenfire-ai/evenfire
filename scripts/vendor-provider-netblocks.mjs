#!/usr/bin/env node
/**
 * issue #299 Phase 2 — vendor the provider-netblocks seed ConfigMap from live
 * provider feeds. Run at release time; range churn then shows up as a reviewable
 * PR diff. The seed guarantees cold-start egress before control-api's first fetch
 * (worst case degrades to Phase-1 /32 behavior, never below).
 *
 * Validates every category through the SAME pure core the runtime uses; exits 1
 * (printing the reasons) rather than ever emitting a bad seed.
 *
 * Usage: node scripts/vendor-provider-netblocks.mjs
 * Output: deploy/base/control-plane/provider-netblocks-configmap.yaml
 */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { createHash } from 'node:crypto'

const require = createRequire(import.meta.url)
const core = require('../packages/network-policy-core/index.cjs')
const registry = require('../packages/network-policy-core/providerRegistry.cjs')

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '..', 'deploy', 'base', 'control-plane', 'provider-netblocks-configmap.yaml')

const TIMEOUT_MS = 10_000
const MAX_BYTES = 8_000_000

// One entry per provider source. Each fetch returns { categories } (both families).
const SOURCES = [
  {
    source: 'github',
    url: 'https://api.github.com/meta',
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'clerum-vendor' },
    categories: ['api', 'web', 'git', 'packages', 'pages'], // excludes `actions`
    parse: body => Object.fromEntries(['api', 'web', 'git', 'packages', 'pages'].map(k => [k, body[k]])),
  },
]

async function fetchJson(url, headers) {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS)
  try {
    const res = await fetch(url, { headers, signal: controller.signal, redirect: 'error' })
    if (res.status !== 200) throw new Error(`${url} → HTTP ${res.status}`)
    const buf = await res.arrayBuffer()
    if (buf.byteLength > MAX_BYTES) throw new Error(`${url} response exceeds ${MAX_BYTES} bytes`)
    return JSON.parse(new TextDecoder().decode(buf))
  } finally {
    clearTimeout(timer)
  }
}

async function main() {
  const data = {}
  const sourcesMeta = {}
  for (const src of SOURCES) {
    const body = await fetchJson(src.url, src.headers)
    const categories = src.parse(body)
    const catMeta = {}
    for (const [cat, list] of Object.entries(categories)) {
      if (!Array.isArray(list)) {
        console.error(`FAIL: ${src.source}.${cat} is missing or not an array`)
        process.exit(1)
      }
      const { ipv4, ipv6, invalid } = core.partitionCidrsByFamily(list)
      if (invalid.length > 0) {
        console.error(`FAIL: ${src.source}.${cat} has malformed CIDRs: ${invalid.join(', ')}`)
        process.exit(1)
      }
      const v = core.validateProviderRanges(ipv4, registry.providerBounds(src.source))
      if (v.kind !== 'ok') {
        console.error(`FAIL: ${src.source}.${cat} failed validation:\n  ${v.reasons.join('\n  ')}`)
        process.exit(1)
      }
      data[`${src.source}.${cat}.ipv4`] = v.ranges.join('\n')
      if (ipv6.length > 0) data[`${src.source}.${cat}.ipv6`] = [...ipv6].sort().join('\n')
      catMeta[cat] = { ipv4: v.ranges.length, ipv6: ipv6.length }
      console.error(`  ${src.source}.${cat}: ${v.ranges.length} IPv4, ${ipv6.length} IPv6`)
    }
    sourcesMeta[src.source] = { fetchedAt: 'seed', etag: null, syncToken: null, sourceUrl: src.url, categories: catMeta }
  }

  const sortedKeys = Object.keys(data).sort()
  const contentHash = createHash('sha256')
    .update(JSON.stringify(sortedKeys.map(k => [k, data[k]])))
    .digest('hex')
  for (const src of Object.keys(sourcesMeta)) sourcesMeta[src].contentHash = contentHash
  data['_meta'] = JSON.stringify({ sources: sourcesMeta, contentHash })

  const yamlData = Object.keys(data)
    .sort()
    .map(k => {
      const lines = data[k].split('\n')
      return `  ${k}: |-\n${lines.map(l => `    ${l}`).join('\n')}`
    })
    .join('\n')

  const yaml = `# GENERATED by scripts/vendor-provider-netblocks.mjs — issue #299 Phase 2.
# Seed provider-netblocks catalog (cold-start; control-api refreshes it live).
# Regenerate with: make vendor-provider-netblocks
apiVersion: v1
kind: ConfigMap
metadata:
  name: clerum-provider-netblocks
  namespace: control-plane
  labels:
    clerum.io/managed-by: control-api
  annotations:
    clerum.io/content-hash: "${contentHash}"
data:
${yamlData}
`
  writeFileSync(OUT, yaml)
  console.error(`\nWrote ${OUT} (contentHash=${contentHash.slice(0, 12)}…)`)
}

main().catch(err => {
  console.error(`FAIL: ${err.message}`)
  process.exit(1)
})
